"""Writes Flip Studio's factory LUTs (effects/color_lut/luts/*.cube).

Each look is a small, documented colour function of our own, sampled on a 17-point 3D grid
(17 is plenty for smooth looks with trilinear interpolation, and keeps each file ~120 KB).
They are made here, not taken from anywhere, so they can ship with the app and the web editor.

    py tools/luts/make_luts.py [output_dir ...]
"""
import math
import os
import sys

SIZE = 17


def clamp(v):
    return 0.0 if v < 0.0 else 1.0 if v > 1.0 else v


def luma(r, g, b):
    return 0.2126 * r + 0.7152 * g + 0.0722 * b


def s_curve(v, amount):
    """Contrast around mid-grey that never clips: a smoothstep blend."""
    s = v * v * (3.0 - 2.0 * v)
    return v + (s - v) * amount


def saturate(r, g, b, k):
    l = luma(r, g, b)
    return l + (r - l) * k, l + (g - l) * k, l + (b - l) * k


def cinematic(r, g, b):
    # Gentle contrast, slightly lifted blacks, a little less colour; cool shadows, warm highs.
    r, g, b = (s_curve(c, 0.35) for c in (r, g, b))
    r, g, b = (0.03 + c * 0.95 for c in (r, g, b))
    r, g, b = saturate(r, g, b, 0.88)
    l = luma(r, g, b)
    r += 0.03 * l - 0.02 * (1 - l)
    b += -0.03 * l + 0.03 * (1 - l)
    return r, g, b


def warm(r, g, b):
    r, g, b = r * 1.06 + 0.015, g * 1.01 + 0.005, b * 0.88
    return saturate(r, g, b, 1.05)


def cold(r, g, b):
    r, g, b = r * 0.9, g * 1.0 + 0.005, b * 1.08 + 0.02
    return saturate(r, g, b, 0.97)


def vintage(r, g, b):
    # Faded film: lifted blacks, rolled-off whites, warm-yellow cast, muted colour.
    r, g, b = saturate(r, g, b, 0.72)
    r, g, b = (0.08 + c * 0.84 for c in (r, g, b))
    r, g, b = r * 1.04 + 0.01, g * 1.0 + 0.01, b * 0.86 + 0.02
    l = luma(r, g, b)
    g += 0.015 * (1 - l)  # a hint of green in the shadows
    return r, g, b


def teal_orange(r, g, b):
    # Split toning: shadows toward teal, highlights (and skin) toward orange, a bit more colour.
    l = luma(r, g, b)
    shadow = (1 - l) ** 1.5
    high = l ** 1.2
    r += -0.06 * shadow + 0.07 * high
    g += 0.02 * shadow + 0.01 * high
    b += 0.06 * shadow - 0.08 * high
    r, g, b = saturate(r, g, b, 1.15)
    return tuple(s_curve(clamp(c), 0.2) for c in (r, g, b))


def black_white(r, g, b):
    # A red-filter black and white with some contrast.
    v = 0.35 * r + 0.55 * g + 0.10 * b
    v = s_curve(clamp(v), 0.3)
    return v, v, v


LOOKS = [
    ("cinematic", "Cinematic", cinematic),
    ("warm", "Warm", warm),
    ("cold", "Cold", cold),
    ("vintage", "Vintage", vintage),
    ("teal_orange", "Teal & Orange", teal_orange),
    ("black_white", "Black & White", black_white),
]


def write(path, title, fn):
    with open(path, "w", encoding="utf-8", newline="\n") as f:
        f.write(f'TITLE "{title}"\n')
        f.write("# Flip Studio factory look, generated by tools/luts/make_luts.py\n")
        f.write(f"LUT_3D_SIZE {SIZE}\n")
        f.write("DOMAIN_MIN 0.0 0.0 0.0\nDOMAIN_MAX 1.0 1.0 1.0\n")
        n = SIZE - 1
        for bi in range(SIZE):
            for gi in range(SIZE):
                for ri in range(SIZE):
                    r, g, b = fn(ri / n, gi / n, bi / n)
                    f.write(f"{clamp(r):.6f} {clamp(g):.6f} {clamp(b):.6f}\n")


def main():
    outs = sys.argv[1:] or [os.path.join(os.path.dirname(__file__), "..", "..", "effects", "color_lut", "luts")]
    for out in outs:
        os.makedirs(out, exist_ok=True)
        for slug, title, fn in LOOKS:
            write(os.path.join(out, slug + ".cube"), title, fn)
        print("wrote", len(LOOKS), "LUTs to", os.path.abspath(out))


if __name__ == "__main__":
    main()
