def m(text: str) -> str:
    """Marks every word (*word*) so it takes the accent look: the small line under or over a title."""
    return " ".join(f"*{w}*" for w in text.split(" "))


def small(color: str = "#ffffff", size: float = 0.3) -> dict:
    """The accent look of the marked words: no rule, just a smaller, other-coloured line."""
    return accent("none", color, size=size)


def shine(speed=0.45, width=0.18, angle=20, intensity=1.0, color="#ffffff") -> dict:
    return fill(fx("shine", "#00000000", speed=speed, width=width, angle=angle, intensity=intensity, colorA=color),
                id="shine", blend="screen")


