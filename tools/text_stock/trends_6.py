def fire(id, es, en, sample, font, size, weight, **kw):
    """Fire-wrapped word: hot gradient, red/orange glow, flicker."""
    layers = kw.pop("layers", None) or [glow("#ff2a00", 0.55, 0.6, id="glow2"), glow("#ff8a00", 0.22, 0.95),
                                        stroke(0.045, "#5a0a00"), fill(FIRE)]
    kw.setdefault("anim_in", tslot("zoom-in", 0.4, "back", **{"from": 35}))
    kw.setdefault("anim_loop", FIRE_LOOP)
    kw.setdefault("card_at", 1.8)
    return trend(id, es, en, sample, font, size, weight, layers, card=DARK,
                 tags=["fuego", "fire", "llamas", *kw.pop("tags", [])], **kw)


