#!/usr/bin/env python3
"""Collect the user-visible names in the bundled catalogs into src/engine/CatalogStrings.cpp.

Effect, transition, audio-effect, template, text-animation and clip-animation names live in JSON, where lupdate
cannot see them. This writes each one as a QT_TRANSLATE_NOOP("Catalog", ...) entry so they land in
i18n/*.ts like any other string; the loaders pass them through drift::catalogText() when they read
the JSON. The generated file is only read by lupdate, never compiled.

Run it from the repo root after adding or renaming a catalog entry, then run lupdate:

    python tools/i18n/catalog_strings.py
"""
import glob
import json
import os

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
OUT = os.path.join(ROOT, "src", "engine", "CatalogStrings.cpp")


def load(path):
    with open(path, encoding="utf-8") as f:
        return json.load(f)


def package_strings(doc, out):
    out.append(doc.get("displayName", ""))
    for p in doc.get("parameters", []):
        out.append(p.get("displayName") or p.get("label") or "")
        out.append(p.get("group", ""))


def text_animation_strings(doc, out):
    out.append(doc.get("label", ""))
    out.append(doc.get("sampleText", ""))
    for p in doc.get("params", []):
        out.append(p.get("label", ""))
        out.append(p.get("group", ""))


# Built into the app rather than read from JSON: the parameters every text reveal shares
# (textAnimationCommonParams in src/core/TextAnimationPreset.cpp).
COMMON_TEXT_ANIMATION_PARAMS = ["Duration", "Stagger", "By", "Order", "Ease", "Your text"]

# Downloaded rather than bundled: the parameter names of Stock's transitions (.driftfx packages
# carry English only). Keep in step with flipstudio-app/src/transitions/stockParamLabels.ts.
STOCK_TRANSITION_PARAMS = [
    "Band Width", "Bars", "Biggest Pixels", "Cells", "Channel Split", "Circles", "Curl Radius",
    "Density", "Depth", "Distance", "Divider", "Dots", "Drips", "Edge Detail", "Edge Softness",
    "Folds", "Gap", "Glow", "Hearts", "Intensity", "Motion Blur", "Pieces", "Pull Back", "Rings",
    "Shake", "Size", "Spikes", "Splatter", "Stagger", "Stars", "Streaks", "Strength", "Stripes",
    "Strokes", "Sweeps", "Swing", "Swirl", "Tear Roughness", "Tiles", "Tilt", "Wave Height",
    "Wobble", "Zoom",
]


def main():
    strings = list(COMMON_TEXT_ANIMATION_PARAMS) + STOCK_TRANSITION_PARAMS
    for pattern in ("effects/*/effect.json", "transitions/*/transition.json",
                    "audio-effects/*/audio-effect.json", "effect-templates/*/template.json"):
        for path in sorted(glob.glob(os.path.join(ROOT, pattern))):
            package_strings(load(path), strings)
    for path in sorted(glob.glob(os.path.join(ROOT, "presets", "text-animations", "*.json"))):
        text_animation_strings(load(path), strings)
    for path in sorted(glob.glob(os.path.join(ROOT, "presets", "clip-animations", "*.json"))):
        strings.append(load(path).get("label", ""))

    seen = set()
    unique = []
    for s in strings:
        if s and s not in seen:
            seen.add(s)
            unique.append(s)

    def cpp(s):
        return '"' + s.replace("\\", "\\\\").replace('"', '\\"').replace("\n", "\\n") + '"'

    lines = [
        "// Generated by tools/i18n/catalog_strings.py from the bundled catalog JSON. Do not edit.",
        "// lupdate reads this file (see qt_add_translations in CMakeLists.txt); nothing compiles it.",
        "#include <QtGlobal>",
        "",
        "[[maybe_unused]] static const char *const kCatalogStrings[] = {",
    ]
    lines += ['    QT_TRANSLATE_NOOP("Catalog", %s),' % cpp(s) for s in unique]
    lines += ["};", ""]
    with open(OUT, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(lines))
    print("%d strings -> %s" % (len(unique), os.path.relpath(OUT, ROOT)))


if __name__ == "__main__":
    main()
