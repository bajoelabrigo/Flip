"""Out › particles: exits where the letters leave in a burst or a trail of particles (prefix op-).

Reading Out: coverage rises 0 -> 1 as a fragment leaves; burst(at=0) fires as it starts to go and
stream() gives particles off while it leaves. Particles are anchored at each letter's home cell, so
a flying letter leaves its trail where it took off. Stagger ease in Out: "easeOut" accelerates away,
"easeIn" leaves fast and settles; EARLY puts a colour change at the start of the leave.
"""

