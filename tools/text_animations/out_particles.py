def color_at_start(color: str) -> dict:
    """The letters take `color` in the first third of their leave."""
    return A([stagger_sel(ease=EARLY)], fillColor=argb(color))


def flicker(amount: float = 15.0, hz: float = 18.0) -> dict:
    """Opacity flicker only while each fragment leaves (the stagger selector gates the noise)."""
    gate = dict(stagger_sel(ease="linear"), mode="add")
    noise = dict(wiggle("character", "noise", hz=hz, phase=57.0, lo=0, hi=100), mode="intersect")
    return A([gate, noise], opacity=amount)


