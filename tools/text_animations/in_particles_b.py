def tint(color: str, mul: float = 1.4, ease: str = "easeOut") -> dict:
    """The letter arrives in `color` and settles to its own fill over `mul` × duration."""
    return A([stagger_sel(mul, ease=ease)], fillColor=argb(color))


def soften(px: float, mul: float = 1.0, ease: str = "easeOut") -> dict:
    return A([stagger_sel(mul, ease=ease)], blur=px)


